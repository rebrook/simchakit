-- ─────────────────────────────────────────────────────────────────────────────
-- SimchaKit V5.1 (R1) — RSVP site backend: private links, settings, stored replies
-- Run in the Supabase SQL editor. Safe to re-run (idempotent).
--
-- RLS IMPACT
--   * household_rsvp_tokens (new): the private link secret for each household, kept
--     in its own table (not a column on households) so viewers, the live-update feed
--     and coordinators can never read it. RLS enabled. Read AND write: event owner and
--     accepted editors only (never on archived events for writes). No anon access.
--   * rsvp_replies (new): what a guest submitted, held for the host to review. RLS
--     enabled. Read: owner, editors and viewers (coordinators excluded, as in M1).
--     Update/delete: owner and editors, never on archived events. NO insert policy:
--     guests never touch the database directly; api/rsvp.js inserts with the service
--     role after validating the token and a schema.
--   * events.rsvp_settings (new jsonb, default {}): covered by existing events policies.
--   * Anon (not signed in) has no policy on any of these, so it cannot select, insert,
--     update or delete.
--
-- DATA IMPACT
--   No backfill. Existing households have no token until the host's first RSVP link
--   is created (lazily, by api/guest). Existing events read rsvp_settings as {}.
--
-- rsvp_settings shape (all optional; missing keys use these defaults):
--   { "allowPlusOnes": false, "maxNewGuests": 2, "autoApply": false, "allowEditUntilDeadline": true }
--   The deadline is NOT stored here: it is the existing Event Details RSVP deadline
--   (events.admin_config.rsvpDeadline), so there is one deadline to keep.
-- ─────────────────────────────────────────────────────────────────────────────

-- 1. Event settings
ALTER TABLE events
  ADD COLUMN IF NOT EXISTS rsvp_settings jsonb NOT NULL DEFAULT '{}'::jsonb;

-- 2. Private tokens: random, 128 bits, generated by the server, never derived from ids
CREATE TABLE IF NOT EXISTS household_rsvp_tokens (
  household_id  uuid PRIMARY KEY REFERENCES households(id) ON DELETE CASCADE,
  event_id      uuid NOT NULL REFERENCES events(id) ON DELETE CASCADE,
  token         text NOT NULL UNIQUE,
  created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS household_rsvp_tokens_event_idx ON household_rsvp_tokens (event_id);

-- 3. Replies, held as proposals the host reviews
CREATE TABLE IF NOT EXISTS rsvp_replies (
  id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  event_id       uuid NOT NULL REFERENCES events(id) ON DELETE CASCADE,
  household_id   uuid NOT NULL REFERENCES households(id) ON DELETE CASCADE,
  submitted_at   timestamptz NOT NULL DEFAULT now(),
  status         text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'accepted', 'rejected')),
  payload        jsonb NOT NULL,
  supersedes     uuid REFERENCES rsvp_replies(id) ON DELETE SET NULL,
  superseded_at  timestamptz              -- set when a newer reply replaced this one
);
CREATE INDEX IF NOT EXISTS rsvp_replies_event_status_idx ON rsvp_replies (event_id, status);
CREATE INDEX IF NOT EXISTS rsvp_replies_household_idx ON rsvp_replies (household_id, submitted_at DESC);
-- A household can have only one pending reply at a time (also guards simultaneous submits).
CREATE UNIQUE INDEX IF NOT EXISTS rsvp_one_pending_per_household
  ON rsvp_replies (household_id) WHERE status = 'pending';

-- 4. RLS
ALTER TABLE household_rsvp_tokens ENABLE ROW LEVEL SECURITY;
ALTER TABLE rsvp_replies          ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS rsvp_tokens_manage ON household_rsvp_tokens;
CREATE POLICY rsvp_tokens_manage ON household_rsvp_tokens FOR ALL TO authenticated
USING (
  EXISTS (SELECT 1 FROM events e WHERE e.id = household_rsvp_tokens.event_id AND NOT e.archived AND (
    e.owner_id = auth.uid()
    OR EXISTS (SELECT 1 FROM event_collaborators c
               WHERE c.event_id = e.id AND c.user_id = auth.uid()
                 AND c.accepted_at IS NOT NULL AND c.role = 'editor')))
)
WITH CHECK (
  EXISTS (SELECT 1 FROM events e WHERE e.id = household_rsvp_tokens.event_id AND NOT e.archived AND (
    e.owner_id = auth.uid()
    OR EXISTS (SELECT 1 FROM event_collaborators c
               WHERE c.event_id = e.id AND c.user_id = auth.uid()
                 AND c.accepted_at IS NOT NULL AND c.role = 'editor')))
);

DROP POLICY IF EXISTS rsvp_replies_read ON rsvp_replies;
CREATE POLICY rsvp_replies_read ON rsvp_replies FOR SELECT TO authenticated USING (
  EXISTS (SELECT 1 FROM events e WHERE e.id = rsvp_replies.event_id AND e.owner_id = auth.uid())
  OR EXISTS (SELECT 1 FROM event_collaborators c
             WHERE c.event_id = rsvp_replies.event_id AND c.user_id = auth.uid()
               AND c.accepted_at IS NOT NULL AND c.role IN ('editor', 'viewer'))
);

DROP POLICY IF EXISTS rsvp_replies_update ON rsvp_replies;
CREATE POLICY rsvp_replies_update ON rsvp_replies FOR UPDATE TO authenticated
USING (
  EXISTS (SELECT 1 FROM events e WHERE e.id = rsvp_replies.event_id AND NOT e.archived AND (
    e.owner_id = auth.uid()
    OR EXISTS (SELECT 1 FROM event_collaborators c
               WHERE c.event_id = e.id AND c.user_id = auth.uid()
                 AND c.accepted_at IS NOT NULL AND c.role = 'editor')))
)
WITH CHECK (
  EXISTS (SELECT 1 FROM events e WHERE e.id = rsvp_replies.event_id AND NOT e.archived AND (
    e.owner_id = auth.uid()
    OR EXISTS (SELECT 1 FROM event_collaborators c
               WHERE c.event_id = e.id AND c.user_id = auth.uid()
                 AND c.accepted_at IS NOT NULL AND c.role = 'editor')))
);

DROP POLICY IF EXISTS rsvp_replies_delete ON rsvp_replies;
CREATE POLICY rsvp_replies_delete ON rsvp_replies FOR DELETE TO authenticated
USING (
  EXISTS (SELECT 1 FROM events e WHERE e.id = rsvp_replies.event_id AND NOT e.archived AND (
    e.owner_id = auth.uid()
    OR EXISTS (SELECT 1 FROM event_collaborators c
               WHERE c.event_id = e.id AND c.user_id = auth.uid()
                 AND c.accepted_at IS NOT NULL AND c.role = 'editor')))
);

