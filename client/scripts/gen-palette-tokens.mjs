// Generates src-v3/styles/palette-tokens.css: the Overview hero and button colors, precomputed per
// palette for light and dark so nothing is computed in the browser (custom palettes are the one
// exception, handled in ThemeProvider). Run: node scripts/gen-palette-tokens.mjs
// Exits non-zero, and prints the table, if any text pair is below 4.5:1.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");

// Palette accents come from the one source of truth.
const themeSrc = readFileSync(join(root, "src-v3/constants/theme.js"), "utf8");
const ACCENTS = {};
for (const m of themeSrc.matchAll(/"?([a-z-]+)"?:\s*\{\s*name: "([^"]+)",\s*accent: "(#[0-9a-f]{6})"/g)) ACCENTS[m[1]] = { name: m[2], accent: m[3] };

// A deep, distinctly different hero background per palette (Navy and Gold uses the brand navy).
const HERO_BG = { "navy-gold": "#0f1d36", rose: "#5a1a34", forest: "#123626", purple: "#2e2150", slate: "#34495f", copper: "#4d2a14", teal: "#0d4547", charcoal: "#2a2a2c", blush: "#5a3a46" };

const SURFACE = { light: "#ffffff", dark: "#1a1714" };   // --bg-surface
const INK = "#1c1614";

const lum = h => { const c = [1, 3, 5].map(i => parseInt(h.slice(i, i + 2), 16) / 255).map(v => v <= 0.03928 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4)); return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]; };
const cr = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };
const mx = (h, t, k) => "#" + [1, 3, 5].map(i => Math.round(parseInt(h.slice(i, i + 2), 16) * (1 - k) + parseInt(t.slice(i, i + 2), 16) * k).toString(16).padStart(2, "0")).join("");

// Filled button: white text if it reaches 4.5:1; otherwise darken the fill up to three 8% steps; otherwise dark ink.
function pick(a) {
  if (cr("#ffffff", a) >= 4.5) return [a, "#ffffff"];
  let f = a;
  for (let i = 0; i < 3; i++) { f = mx(f, "#000000", 0.08); if (cr("#ffffff", f) >= 4.5) return [f, "#ffffff"]; }
  return cr(INK, a) >= 4.5 ? [a, INK] : [mx(a, "#000000", 0.3), "#ffffff"];
}
// Accent as text on paper: darken (light) or lighten (dark) until 4.5:1.
function accentInk(a, surf, dark) { let t = a; for (let i = 0; i < 14 && cr(t, surf) < 4.5; i++) t = mx(t, dark ? "#ffffff" : "#000000", 0.1); return t; }
// Hero: lifted background in dark mode; accent lightened until 4.5:1 on it; text derived from the background.
function hero(a, key, dark) {
  const bg = dark ? mx(HERO_BG[key], "#ffffff", 0.12) : HERO_BG[key];
  let h = a; for (let i = 0; i < 14 && cr(h, bg) < 4.5; i++) h = mx(h, "#ffffff", 0.1);
  return { bg, accent: h, text: mx(bg, "#ffffff", 0.94), text2: mx(bg, "#ffffff", 0.82), onAccent: cr(INK, h) >= 4.5 ? INK : bg };
}
const RED = { light: "#9b2335", dark: "#f87171" };   // --red in base.css

let css = `/* GENERATED by scripts/gen-palette-tokens.mjs. Do not edit by hand.
   Overview hero and button colors, precomputed per palette, light and dark (V5.9.0).
   Every text pair is at least 4.5:1; the script fails if one is not. */\n`;
const rows = []; let failed = false;
const check = (label, ratio) => { if (ratio < 4.5) failed = true; return `${ratio >= 4.5 ? "pass" : "FAIL"} ${ratio.toFixed(1)}`; };

for (const [key, { name, accent }] of Object.entries(ACCENTS)) {
  const row = [name];
  for (const theme of ["light", "dark"]) {
    const dark = theme === "dark";
    const [fill, onFill] = pick(accent);
    const ink = accentInk(accent, SURFACE[theme], dark);
    const H = hero(accent, key, dark);
    css += `:root${dark ? '[data-theme="dark"]' : ""}[data-palette="${key}"] {
  --hero-bg: ${H.bg}; --hero-accent: ${H.accent}; --hero-text: ${H.text}; --hero-text-2: ${H.text2}; --hero-on-accent: ${H.onAccent};
  --accent-ink: ${ink}; --accent-fill: ${fill}; --on-accent: ${onFill};
}\n`;
    row.push(check("hero accent", cr(H.accent, H.bg)), check("hero text", cr(H.text, H.bg)), check("hero text 2", cr(H.text2, H.bg)), check("on hero accent", cr(H.onAccent, H.accent)), check("ink", cr(ink, SURFACE[theme])), check("button", cr(onFill, fill)));
  }
  rows.push(row);
}
// Fallback before ThemeProvider has set data-palette: Rose, so the hero is never unstyled.
for (const theme of ["light", "dark"]) {
  const dark = theme === "dark";
  const a = ACCENTS.rose.accent, [fill, onFill] = pick(a), H = hero(a, "rose", dark);
  css += `:root:not([data-palette])${dark ? '[data-theme="dark"]' : ""} {
  --hero-bg: ${H.bg}; --hero-accent: ${H.accent}; --hero-text: ${H.text}; --hero-text-2: ${H.text2}; --hero-on-accent: ${H.onAccent};
  --accent-ink: ${accentInk(a, SURFACE[theme], dark)}; --accent-fill: ${fill}; --on-accent: ${onFill};
}\n`;
}
for (const theme of ["light", "dark"]) {
  const [rf, ro] = pick(RED[theme]);
  css += `:root${theme === "dark" ? '[data-theme="dark"]' : ""} { --red-fill: ${rf}; --on-red: ${ro}; }\n`;
  rows.push([`red (${theme})`, check("red button", cr(ro, rf))]);
}
writeFileSync(join(root, "src-v3/styles/palette-tokens.css"), css);
console.log("palette | light: hero accent, text, text2, on-accent, accent text, button | dark: same");
rows.forEach(r => console.log(r.join(" | ")));
if (failed) { console.error("\nAt least one pair is below 4.5:1"); process.exit(1); }
console.log("\nAll pairs pass 4.5:1");
